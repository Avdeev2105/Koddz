#include <stdio.h>

int main(void)
{
    float x = 60.0f;   /* цена за литр молока в марте, руб. */
    float a = 10.0f;   /* повышение цены с 1 апреля, руб.  */
    int   K = 4;       /* литров молока в день             */
    int   D = 30;      /* дней в апреле                    */

    float P, V, S;     /* цена, объём, сумма               */

    P = x + a;         /* цена в апреле, руб./л            */
    V = K * D;         /* всего литров за апрель           */
    S = V * P;         /* сумма к оплате за апрель, руб.   */

    printf("Цена в марте:        %.2f руб./л\n", x);
    printf("Цена в апреле:       %.2f руб./л\n", P);
    printf("Доставлено за апрель:%d л\n", (int)V);
    printf("Сумма к оплате:      %.2f руб.\n", S);

    return 0;
}
